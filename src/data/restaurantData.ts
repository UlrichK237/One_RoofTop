export interface Plat {
  id: string;
  nom: string;
  description: string;
  prix: number;
  prixBouteille?: number | null;
  options?: string[];
  prixOptions?: Record<string, number>;
  sousSection?: string;
  note?: string;
}

export interface CategorieMenu {
  categorie: string;
  univers: 'cuisine' | 'cocktails' | 'cave';
  etage: string;
  libelle_fr: string;
  libelle_en: string;
  sous_titre?: string;
  plats: Plat[];
}

export interface HoraireJour {
  jour: string;
  jourIndex: number; // 0 = dimanche, 1 = lundi, ..., 6 = samedi
  ouverture: string; // HH:MM
  fermeture: string; // HH:MM (peut être après minuit, ex. "02:00")
  ferme?: boolean;
}

